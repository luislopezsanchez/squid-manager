def recopilar(db, segundos: int = 86400) -> dict:
    tot = ru.totales_actividad(segundos, None, None)
    top_u = ru.top_users(5, "bytes", segundos, None, None)
    top_d = ru.top_domains(5, False, "bytes", segundos, None, None)
    top_bd = ru.top_domains(5, True, "requests", segundos, None, None)
    top_bu, _sin = ru.top_blocked_users(5, segundos, None, None)
    cache = ru.cache_resumen(segundos, None, None)
    req = int(sum(x["requests"] for x in ru.serie_total(segundos, None, None)))
    desde = time.time() - segundos

    from app.services.quota_service import cuotas_excedidas
    cuotas = [c for c in cuotas_excedidas(db) if (c.get("excedida_en") or 0) >= desde or c.get("excedida_en") is None]

    from app.services.anomaly_service import get_anomalias_recientes
    alertas = get_anomalias_recientes(segundos / 3600, 15)
    return {
        "totales": tot, "peticiones": req, "cache": cache,
        "top_usuarios": top_u, "top_sitios": top_d, "top_bloqueados": top_bd, "top_bloqueos_usuarios": top_bu,
        "cuotas": cuotas, "alertas": alertas,
    }


def _tabla(filas: list[tuple[str, str]], vacio: str) -> str:
    if not filas:
        return f'<p style="margin:0;color:#6b7c88;font-size:13px">{html.escape(vacio)}</p>'
    out = ['<table role="presentation" width="100%" cellspacing="0" cellpadding="0" style="font-size:13px">']
    for i, (a, b) in enumerate(filas):
        bg = "#f5f9fc" if i % 2 == 0 else "#ffffff"
        out.append(
            f'<tr style="background:{bg}"><td style="padding:7px 10px;color:#1c2b36">{html.escape(a)}</td>'
            f'<td style="padding:7px 10px;text-align:right;color:#0B497C;font-weight:600;white-space:nowrap">{html.escape(b)}</td></tr>'
        )
    out.append("</table>")
    return "".join(out)


def _seccion(titulo: str, cuerpo: str) -> str:
    return (f'<div style="margin:0 0 22px"><h3 style="margin:0 0 8px;font-size:14px;color:#0B497C;'
            f'border-bottom:2px solid #e3edf4;padding-bottom:5px">{html.escape(titulo)}</h3>{cuerpo}</div>')


def _tarjeta(valor: str, etiqueta: str) -> str:
    return (f'<td style="width:33%;padding:6px"><div style="background:#f0f6fb;border-radius:10px;padding:14px 8px;text-align:center">'
            f'<div style="font-size:22px;font-weight:700;color:#0B497C">{html.escape(valor)}</div>'
            f'<div style="font-size:11.5px;color:#56697a;margin-top:2px">{html.escape(etiqueta)}</div></div></td>')


def construir(datos: dict, idioma: str = "es", ahora: datetime | None = None) -> tuple[str, str, str]:
    """(asunto, html, texto plano)."""
    t = _T.get(idioma, _T["es"])
    ahora = ahora or tzs.ahora_local()
    fecha = ahora.strftime("%Y-%m-%d %H:%M")
    tot = datos["totales"]
    d = datos

    tarjetas = (
        "<tr>" + _tarjeta(_fmt_n(tot["usuarios"]["count"]), t["usuarios"])
        + _tarjeta(_fmt_n(tot["dominios"]["count"]), t["sitios"])
        + _tarjeta(_fmt_bytes(tot["usuarios"]["bytes"]), t["datos"]) + "</tr><tr>"
        + _tarjeta(_fmt_n(d["peticiones"]), t["peticiones"])
        + _tarjeta(_fmt_n(tot["usuarios_bloqueados_requests"]), t["bloqueadas"])
        + _tarjeta(f'{d["cache"]["cache_hit_ratio"]} %' if d["cache"]["cache_hit_ratio"] is not None else "—", t["cache"]) + "</tr>"
    )
    req = t["req"]
    cuotas = []
    for c in d["cuotas"]:
        est = t["cortada"] if c["quota_action_applied"] and c["quota_action"] == "cut" else (
            t["limitada"] if c["quota_action_applied"] else t["activa"])
        cuotas.append((f'{c["nombre"]} ({t[c["tipo"]]})', f'{_fmt_bytes(c["quota_bytes_used"])} / {_fmt_bytes(c["quota_bytes"])} · {est}'))
    alertas = [(a["asunto"].replace("SquidManager: ", ""), a["mensaje"][:110]) for a in d["alertas"]]

    cuerpo = (
        f'<table role="presentation" width="100%" cellspacing="0" cellpadding="0" style="margin:0 0 20px">{tarjetas}</table>'
        + _seccion(t["top_usuarios"], _tabla([(u["user"], f'{_fmt_bytes(u["bytes"])} · {_fmt_n(u["requests"])} {req}') for u in d["top_usuarios"]], t["nada"]))
        + _seccion(t["top_sitios"], _tabla([(x["domain"], f'{_fmt_bytes(x["bytes"])} · {_fmt_n(x["requests"])} {req}') for x in d["top_sitios"]], t["nada"]))
        + _seccion(t["top_bloq"], _tabla([(x["domain"], f'{_fmt_n(x["requests"])} {req}') for x in d["top_bloqueados"]], t["nada"]))
        + _seccion(t["top_bloq_u"], _tabla([(u, _fmt_n(n)) for u, n in d["top_bloqueos_usuarios"]], t["nada"]))
        + _seccion(t["cuotas"], _tabla(cuotas, t["sin_cuotas"]))
        + _seccion(t["alertas"], _tabla(alertas, t["sin_alertas"]))
    )
    cuerpo_html = (
        '<!doctype html><html><body style="margin:0;background:#eef3f7;font-family:Segoe UI,Helvetica,Arial,sans-serif">'
        '<table role="presentation" width="100%" cellspacing="0" cellpadding="0"><tr><td align="center" style="padding:24px 12px">'
        '<table role="presentation" width="620" cellspacing="0" cellpadding="0" style="max-width:620px;background:#fff;border-radius:14px;overflow:hidden">'
        f'<tr><td style="background:#0B497C;padding:22px 26px"><div style="color:#fff;font-size:20px;font-weight:700">{html.escape(t["titulo"])}</div>'
        f'<div style="color:#b9d3e6;font-size:12.5px;margin-top:4px">{html.escape(t["desde"])}: 24 h · {html.escape(fecha)} ({html.escape(str(tzs.get_tz()))})</div></td></tr>'
        f'<tr><td style="padding:22px 26px">{cuerpo}</td></tr>'
        f'<tr><td style="padding:14px 26px;background:#f5f9fc;color:#7a8b97;font-size:11.5px">{html.escape(t["pie"])}</td></tr>'
        "</table></td></tr></table></body></html>"
    )

    lineas = [t["titulo"], f'{t["desde"]}: 24 h · {fecha}', "",
              f'{t["usuarios"]}: {tot["usuarios"]["count"]}', f'{t["sitios"]}: {tot["dominios"]["count"]}',
              f'{t["datos"]}: {_fmt_bytes(tot["usuarios"]["bytes"])}', f'{t["peticiones"]}: {d["peticiones"]}',
              f'{t["bloqueadas"]}: {tot["usuarios_bloqueados_requests"]}', ""]
    for titulo, filas in (
        (t["top_usuarios"], [(u["user"], _fmt_bytes(u["bytes"])) for u in d["top_usuarios"]]),
        (t["top_sitios"], [(x["domain"], _fmt_bytes(x["bytes"])) for x in d["top_sitios"]]),
        (t["top_bloq"], [(x["domain"], str(x["requests"])) for x in d["top_bloqueados"]]),
        (t["cuotas"], cuotas), (t["alertas"], alertas)):
        lineas.append(titulo + ":")
        lineas += [f"  - {a}: {b}" for a, b in filas] or ["  -"]
        lineas.append("")
    return f'SquidManager: {t["asunto"]} {ahora.strftime("%Y-%m-%d")}', cuerpo_html, "\n".join(lineas)


