def _app_get(db, k: str) -> str | None:
    r = db.execute(text("SELECT v FROM app_settings WHERE k=:k"), {"k": k}).fetchone()
    return r[0] if r else None


def _app_set(db, k: str, v: str) -> None:
    db.execute(text("INSERT INTO app_settings (k,v) VALUES (:k,:v) ON CONFLICT (k) DO UPDATE SET v=EXCLUDED.v"),
               {"k": k, "v": v})


def guardar_idioma(db, idioma: str) -> None:
    if idioma in _T:
        _app_set(db, _CLAVE_IDIOMA, idioma)


def destinatarios(db) -> list[str]:
    from app.models.admin import Admin
    return sorted({a.email.strip() for a in db.query(Admin).filter(Admin.is_active == True).all()  # noqa: E712
                   if a.email and "@" in a.email})


def condiciones(db) -> dict:
    """Qué falta para poder activar el reporte."""
    from app.models.smtp_config import SmtpConfig
    smtp = db.query(SmtpConfig).first()
    smtp_ok = bool(smtp and smtp.smtp_host and (smtp.smtp_from or smtp.smtp_user))
    dest = destinatarios(db)
    return {"smtp": smtp_ok, "admin_con_email": bool(dest), "destinatarios": dest, "ok": smtp_ok and bool(dest)}


