def enviar(db, forzar: bool = False) -> dict:
    from app.models.smtp_config import SmtpConfig
    from app.services.notification_service import _enviar_smtp, _snapshot_config
    from app.models.notification_config import NotificationConfig

    cond = condiciones(db)
    if not cond["ok"]:
        return {"ok": False, "message": "Falta configurar el SMTP o un correo en la cuenta de administrador"}
    cfg = db.query(NotificationConfig).first()
    smtp = db.query(SmtpConfig).first()
    snap = _snapshot_config(cfg, smtp)
    idioma = _app_get(db, _CLAVE_IDIOMA) or "es"
    asunto, cuerpo_html, texto = construir(recopilar(db), idioma)
    ok, msg = _enviar_smtp(snap, cond["destinatarios"], asunto, texto, html_body=cuerpo_html)
    return {"ok": ok, "message": msg}


def _tick() -> None:
    db = SessionLocal()
    try:
        from app.models.notification_config import NotificationConfig
        cfg = db.query(NotificationConfig).first()
        if not cfg or not cfg.daily_report_enabled:
            return
        ahora = tzs.ahora_local()
        try:
            hh, mm = (int(x) for x in (cfg.daily_report_time or "23:55").split(":"))
        except ValueError:
            hh, mm = 23, 55
        hoy = ahora.strftime("%Y-%m-%d")
        if _app_get(db, _CLAVE_ULTIMO) == hoy:
            return
        if (ahora.hour, ahora.minute) < (hh, mm):
            return
        # Marca primero: si el envío falla no se reintenta cada 30 s durante todo el día.
        _app_set(db, _CLAVE_ULTIMO, hoy)
        db.commit()
        r = enviar(db)
        if r["ok"]:
            logger.info("Reporte diario enviado: %s", r["message"])
        else:
            logger.warning("Reporte diario no enviado: %s", r["message"])
    finally:
        db.close()


def _loop() -> None:
    time.sleep(20)
    while True:
        try:
            _tick()
        except Exception as e:
            logger.error("Error en el reporte diario: %s", e)
        time.sleep(_POLL)


def start_daily_report() -> None:
    threading.Thread(target=_loop, name="daily-report", daemon=True).start()
